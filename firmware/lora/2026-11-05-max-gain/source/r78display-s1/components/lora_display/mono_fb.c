static const uint8_t *glyph(char c)
{
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    const uint8_t *unknown = NULL;
    for (size_t i = 0; i < sizeof font / sizeof font[0]; i++) {
        if (font[i].c == c) return font[i].col;
        if (font[i].c == '?') unknown = font[i].col;
    }
    return unknown;
}

void mono_fb_clear(mono_fb_t *fb) { memset(fb->buf, 0, sizeof fb->buf); }

int mono_fb_get(const mono_fb_t *fb, int x, int y)
{
    if (x < 0 || x >= MONO_FB_W || y < 0 || y >= MONO_FB_H) return 0;
    return (fb->buf[(y / 8) * MONO_FB_W + x] >> (y % 8)) & 1;
}

void mono_fb_char(mono_fb_t *fb, int col, int row, char c)
{
    if (row < 0 || row >= MONO_FB_H / 8 || col < 0 || col > (MONO_FB_W - 1) / 6) return;
    const uint8_t *g = glyph(c);
    int x0 = col * 6;
    for (int i = 0; i < 6; i++) {
        int x = x0 + i;
        if (x >= MONO_FB_W) return;
        fb->buf[row * MONO_FB_W + x] = i < 5 ? g[i] : 0x00;
    }
}

void mono_fb_text(mono_fb_t *fb, int col, int row, const char *s)
{
    if (row < 0 || row >= MONO_FB_H / 8 || col < 0) return;
    for (; s && *s && col <= (MONO_FB_W - 1) / 6; s++, col++)
        mono_fb_char(fb, col, row, *s);
}
