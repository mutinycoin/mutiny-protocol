#!/usr/bin/env perl
# Signing-call TRIPWIRE for non-test wallet-core and desktop code (fixes of the independent wallet
# review, MAJOR-2; docs/BUILD-CONFIGURATIONS-V1.md section 14). Called by build/check-shipping-config.sh
# in git and in package mode; build/negative-controls.sh injects every FAIL probe of
# build/signing-call-probes.txt into a scratch clone and requires that script to fail.
#
# This is a tripwire, not a proof. The PROPERTY is the type system: a key reaches a signature only
# through `Signer::authorize`, whose handlers get it through the crate-private `KindSigner` (domain
# fixed by kind and purpose), with a single-use `Approval` that is not `Clone`, has private fields
# and is constructed only by the review gate. The tripwire catches a NEW call site that could sign
# outside that path (a raw `HybridKey::sign`, a consensus signing routine such as
# `Transfer::sign_input`, `Operation::approve`, `Rotation::sign`, `SignedClaim::sign`,
# `OfferProof::sign`, `SignedOffer::sign`, ...) whatever the receiver is called, by matching CALL
# SYNTAX in the lexed source and naming the function that contains it; a call that is not on the
# EXACT allow-list of build/signing-call-rules.txt (file, function, callee, number of calls) fails.
#
# Model: the lexer and the model of test code of build/check-host-independence.pl (shared:
# build/rust-source-model.pl), so comments, string, raw-string and char literals and test items are
# not code; in addition a test-only `mod name;` declaration (no #[path]) makes its file a test file.
# A line break is a space, so a method chain split over lines is read like any other. For each
# call this script finds the innermost enclosing `fn NAME { .. }` (closures belong to their `fn`).
# Every name `callee` lists and every name starting with a `prefix` of the rules file is a signing
# name; a signing call is `.name(`, `.name::<..>(`, any path segment `::name` (called or used as a
# value, `<T as U>::name` included) or a bare `name(` that is not its definition `fn name(`. A
# `Domain::` path inside the arguments of a signing call is a finding on its own, even on an allowed
# call (no allowed call site names a domain: `KindSigner` derives it from the kind and purpose).
# Known limits: macro_rules! bodies and code generated by macros are not seen; a `{` inside a
# generic default of a `fn` signature would be read as the start of its body; a signing routine
# reached through a trait object or a renamed import (`use x::sign as s; s(..)`) is not a call by
# name (a renamed import still shows up as the path segment `::sign`).
#
# Usage: perl build/check-signing-calls.pl [--root DIR] [--selftest | --dump]
#   default     scan wallet-core/src and desktop/src; print "FINDING <file>:<line>: ..." per finding
#               and "SUMMARY ..."; exit 0 only if there is no finding (stale allow entries count).
#   --selftest  run every probe of build/signing-call-probes.txt; print "PROBE <id> expected <X>
#               got <Y> ok|MISMATCH"; exit 0 only if every probe reaches its expected verdict.
#   --dump      print "<file>:<line>: <function> <callee> <syntax>" for every signing call found.
use strict;
use warnings;
use Cwd ();
use File::Spec ();
use FindBin ();
BEGIN {
    require "$FindBin::Bin/rust-source-model.pl";
    no strict 'refs';
    *{"main::$_"} = \&{"RustSourceModel::$_"} for qw(slurp lex regions all_paths);
}

my ($root, $mode) = (undef, 'scan');
while (@ARGV) {
    my $a = shift @ARGV;
    if ($a eq '--root') { $root = shift @ARGV; }
    elsif ($a eq '--selftest') { $mode = 'selftest'; }
    elsif ($a eq '--dump') { $mode = 'dump'; }
    else { die "unknown argument $a\n"; }
}
unless (defined $root) {
    my ($vol, $dir) = File::Spec->splitpath(File::Spec->rel2abs($0));
    $root = File::Spec->catpath($vol, File::Spec->catdir($dir, File::Spec->updir), '');
}
$root = Cwd::abs_path($root) // die "root not found\n";
my @SCAN = ('wallet-core/src', 'desktop/src');

# ---- rules ---------------------------------------------------------------------------------------
my (@names, @prefixes, %allow, @allow_order);
for my $raw (split /\n/, slurp("$root/build/signing-call-rules.txt")) {
    (my $l = $raw) =~ s/\r$//;
    next if $l =~ /^\s*(#|$)/;
    if ($l =~ /^callee\s+([A-Za-z_][A-Za-z0-9_]*)\s*$/) { push @names, $1; }
    elsif ($l =~ /^prefix\s+([A-Za-z_][A-Za-z0-9_]*)\s*$/) { push @prefixes, $1; }
    elsif ($l =~ /^allow\s+(\S+)\s+([A-Za-z_][A-Za-z0-9_]*)\s+([A-Za-z_][A-Za-z0-9_]*)\s+([1-9][0-9]*)\s*$/) {
        my $key = "$1\t$2\t$3";
        die "build/signing-call-rules.txt: duplicate allow entry: $l\n" if exists $allow{$key};
        $allow{$key} = $4; push @allow_order, $key;
    }
    else { die "build/signing-call-rules.txt: malformed line: $l\n"; }
}
die "no signing names\n" unless @names || @prefixes;
my $NAME = '(?:' . join('|', (map { quotemeta } @names), (map { quotemeta($_) . '[A-Za-z0-9_]*' } @prefixes)) . ')(?![A-Za-z0-9_])';

# ---- analysis ------------------------------------------------------------------------------------
# The code of a file with test items and literals blanked out and line breaks as spaces, with the
# line of every character; plus the test-only #[path] values and `mod name;` declarations.
sub masked {
    my ($text) = @_;
    my ($L, $C, $T) = lex($text);
    my ($test, $paths) = regions($C, $T);
    my ($code, $test_code, @line) = ('', '');
    my $prev = 0;
    for my $k (0 .. $#$C) {
        if ($L->[$k] != $prev) { $code .= ' '; push @line, $L->[$k]; $prev = $L->[$k]; $test_code .= ' '; }
        $code .= ($test->[$k] || $T->[$k]) ? ' ' : $C->[$k];
        $test_code .= ($test->[$k] && !$T->[$k]) ? $C->[$k] : ' ';
        push @line, $L->[$k];
    }
    my @mods;
    push @mods, $1 while $test_code =~ /(?<![A-Za-z0-9_])mod\s+([A-Za-z_][A-Za-z0-9_]*)\s*;/g;
    return ($code, \@line, $paths, \@mods, $C, $T);
}

# [start, end, name] of every `fn` body.
sub functions {
    my ($code) = @_;
    my %fn_at;
    while ($code =~ /(?<![A-Za-z0-9_])fn\s+([A-Za-z_][A-Za-z0-9_]*)/g) { $fn_at{$-[0]} = [$1, $+[0]]; }
    my (@stack, @frames, $pending);
    my ($depth, $paren) = (0, 0);
    my $n = length $code;
    for (my $i = 0; $i < $n; $i++) {
        if (my $f = $fn_at{$i}) { $pending = $f->[0]; $paren = 0; $i = $f->[1] - 1; next; }
        my $ch = substr($code, $i, 1);
        if ($ch eq '(' || $ch eq '[') { $paren++ if defined $pending; }
        elsif ($ch eq ')' || $ch eq ']') { $paren-- if defined $pending && $paren > 0; }
        elsif ($ch eq ';') { undef $pending if defined $pending && $paren == 0; }
        elsif ($ch eq '{') {
            $depth++;
            if (defined $pending && $paren == 0) { push @stack, [$pending, $depth, $i]; undef $pending; }
        }
        elsif ($ch eq '}') {
            if (@stack && $stack[-1][1] == $depth) { my $f = pop @stack; push @frames, [$f->[2], $i, $f->[0]]; }
            $depth-- if $depth > 0;
        }
    }
    push @frames, [$_->[2], $n, $_->[0]] for @stack;
    return \@frames;
}

sub enclosing {
    my ($frames, $at) = @_;
    my ($best, $width) = ('<file scope>', undef);
    for my $f (@$frames) {
        next unless $f->[0] <= $at && $at <= $f->[1];
        my $w = $f->[1] - $f->[0];
        ($best, $width) = ($f->[2], $w) if !defined $width || $w < $width;
    }
    return $best;
}

# The argument text of the call whose `(` is at $open (to the matching `)`).
sub arguments {
    my ($code, $open) = @_;
    my $depth = 0;
    for (my $i = $open; $i < length $code; $i++) {
        my $ch = substr($code, $i, 1);
        $depth++ if $ch eq '(';
        if ($ch eq ')') { $depth--; return substr($code, $open, $i - $open + 1) if $depth == 0; }
    }
    return substr($code, $open);
}

# Every signing call of a file: { line, fn, callee, syntax, domain }.
sub calls_in {
    my ($text) = @_;
    my ($code, $line, $paths, $mods) = masked($text);
    my $frames = functions($code);
    my (@out, %seen);
    my $add = sub {
        my ($at, $callee, $syntax, $open) = @_;
        return if $seen{$at}++;
        my $args = defined $open ? arguments($code, $open) : '';
        push @out, { line => $line->[$at], fn => enclosing($frames, $at), callee => $callee,
                     syntax => $syntax, domain => scalar($args =~ /(?<![A-Za-z0-9_])Domain\s*::/) };
    };
    my $generic = '(?:::\s*<[^(){};]*?>\s*)?';
    while ($code =~ /\.\s*($NAME)\s*$generic(\()/g) { $add->($-[1], $1, 'method', $-[2]); }
    while ($code =~ /::\s*($NAME)(?:\s*$generic(\())?/g) { $add->($-[1], $1, 'path', $-[2]); }
    # A bare call: the name not after `.` or `::` (the two forms above) and not its definition.
    while ($code =~ /(?<![A-Za-z0-9_])($NAME)\s*$generic(\()/g) {
        my ($at, $callee, $open) = ($-[1], $1, $-[2]);
        my $before = substr($code, 0, $at);
        next if $before =~ /[.:]\s*\z/ || $before =~ /(?<![A-Za-z0-9_])fn\s*\z/;
        $add->($at, $callee, 'bare', $open);
    }
    return (\@out, $paths, $mods);
}

# Findings for one file text scanned as the repository-relative path $rel, and the counts per
# (file, function, callee) for the stale-entry check.
sub findings {
    my ($rel, $text, $counts) = @_;
    my ($calls) = calls_in($text);
    my %group;
    for my $c (@$calls) { push @{ $group{"$rel\t$c->{fn}\t$c->{callee}"} }, $c; }
    my @out;
    for my $key (sort keys %group) {
        my $found = @{ $group{$key} };
        $counts->{$key} = $found if $counts;
        my $allowed = $allow{$key} // 0;
        my (undef, $fn, $callee) = split /\t/, $key;
        if ($found > $allowed) {
            for my $c (@{ $group{$key} }) {
                push @out, sprintf("%s:%d: signing call '%s' (%s) in fn %s: %d in this function, the allow-list permits %d",
                    $rel, $c->{line}, $callee, $c->{syntax}, $fn, $found, $allowed);
            }
        }
        for my $c (@{ $group{$key} }) {
            push @out, sprintf("%s:%d: a Domain:: path inside the arguments of the signing call '%s' in fn %s",
                $rel, $c->{line}, $callee, $fn) if $c->{domain};
        }
    }
    return @out;
}

# ---- probes --------------------------------------------------------------------------------------
if ($mode eq 'selftest') {
    my (@probes, $cur);
    for my $raw (split /\n/, slurp("$root/build/signing-call-probes.txt")) {
        (my $l = $raw) =~ s/\r$//;
        if ($l =~ /^=== (\S+) (PASS|FAIL)(?: @(\S+))? (.*)$/) {
            $cur = { id => $1, want => $2, file => $3 // 'wallet-core/src/ops/payment.rs', what => $4, text => '' };
            push @probes, $cur; next;
        }
        next unless $cur;
        $cur->{text} .= "$l\n";
    }
    die "no probes\n" unless @probes;
    my $bad = 0;
    for my $p (@probes) {
        my @f = findings($p->{file}, $p->{text});
        my $got = @f ? 'FAIL' : 'PASS';
        my $ok = $got eq $p->{want};
        $bad++ unless $ok;
        printf "PROBE %s expected %s got %s %s (%s)\n", $p->{id}, $p->{want}, $got, $ok ? 'ok' : 'MISMATCH', $p->{what};
    }
    printf "SELFTEST %d probe(s), %d mismatch(es)\n", scalar @probes, $bad;
    exit($bad ? 1 : 0);
}

# ---- the shipped tree ----------------------------------------------------------------------------
my @files;
sub walk {
    my ($dir) = @_;
    opendir(my $d, $dir) or die "$dir: $!\n";
    for my $e (sort grep { $_ ne '.' && $_ ne '..' } readdir $d) {
        my $p = "$dir/$e";
        if (-d $p) { walk($p); } elsif ($e =~ /\.rs$/) { push @files, $p; }
    }
    closedir $d;
}
walk("$root/$_") for @SCAN;
die "too few Rust files under @SCAN\n" if @files < 40;
sub canon { my ($base, $p) = @_; my $full = "$base/$p"; return -e $full ? Cwd::abs_path($full) : undef; }
sub dirname_of { my ($p) = @_; (my $d = $p) =~ s{/[^/]*$}{}; return $d; }
# The directory a file's `mod name;` declarations resolve from (rustc: a crate root or mod.rs
# declares next to itself, any other file in the directory named after its stem).
sub module_dir {
    my ($p) = @_;
    my ($dir, $file) = $p =~ m{^(.*)/([^/]*)$};
    return $dir if $file =~ /^(main|lib|mod)\.rs$/;
    (my $stem = $file) =~ s/\.rs$//;
    return "$dir/$stem";
}
my (%text, %test_file, @queue);
for my $f (@files) {
    $text{$f} = slurp($f);
    my (undef, $paths, $mods) = calls_in($text{$f});
    for my $p (@$paths) {
        my $c = canon(dirname_of($f), $p);
        if (defined $c && !$test_file{$c}++) { push @queue, $c; }
    }
    for my $m (@$mods) {
        for my $candidate ("$m.rs", "$m/mod.rs") {
            my $c = canon(module_dir($f), $candidate);
            if (defined $c && !$test_file{$c}++) { push @queue, $c; }
        }
    }
}
while (defined(my $t = shift @queue)) {
    next unless -f $t;
    my ($L, $C, $T) = lex(slurp($t));
    for my $p (all_paths($C, $T)) {
        my $c = canon(dirname_of($t), $p);
        if (defined $c && !$test_file{$c}++) { push @queue, $c; }
    }
}
my @shipped = grep { !$test_file{Cwd::abs_path($_)} } @files;
my $rel = sub { my ($f) = @_; (my $r = $f) =~ s{^\Q$root\E/}{}; return $r; };
if ($mode eq 'dump') {
    for my $f (@shipped) {
        my ($calls) = calls_in($text{$f});
        printf "%s:%d: %s %s %s%s\n", $rel->($f), $_->{line}, $_->{fn}, $_->{callee}, $_->{syntax},
            $_->{domain} ? ' DOMAIN' : '' for @$calls;
    }
    exit 0;
}
my (@found, %counts);
my $nlines = 0;
for my $f (@shipped) {
    my %lines;
    my ($code, $line) = masked($text{$f});
    for my $i (0 .. length($code) - 1) { $lines{$line->[$i]} = 1 if substr($code, $i, 1) =~ /\S/; }
    $nlines += keys %lines;
    push @found, findings($rel->($f), $text{$f}, \%counts);
}
for my $key (@allow_order) {
    my ($file, $fn, $callee) = split /\t/, $key;
    my $have = $counts{$key} // 0;
    push @found, "build/signing-call-rules.txt: stale allow entry ($file fn $fn callee $callee permits $allow{$key}, $have found)"
        if $have < $allow{$key};
}
print "FINDING $_\n" for @found;
printf "SUMMARY scanned %d shipped file(s) (%d test file(s) excluded), %d non-test line(s), %d signing name(s) and %d prefix(es), %d allow entr%s: %d finding(s)\n",
    scalar @shipped, scalar(@files) - scalar(@shipped), $nlines, scalar @names, scalar @prefixes,
    scalar @allow_order, @allow_order == 1 ? 'y' : 'ies', scalar @found;
die "too few shipped lines scanned: $nlines\n" if $nlines < 15000;
exit(@found ? 1 : 0);
